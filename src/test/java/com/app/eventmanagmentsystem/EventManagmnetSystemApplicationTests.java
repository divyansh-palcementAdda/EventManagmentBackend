package com.app.eventmanagmentsystem;

import com.app.eventmanagmentsystem.model.Event;
import com.app.eventmanagmentsystem.model.enums.ActivationPolicy;
import com.app.eventmanagmentsystem.model.enums.CheckInPolicy;
import com.app.eventmanagmentsystem.model.enums.EventStatus;
import com.app.eventmanagmentsystem.repository.EventRepository;
import com.app.eventmanagmentsystem.util.EventCodeGenerator;
import com.app.eventmanagmentsystem.util.PassSeriesCodeGenerator;
import com.app.eventmanagmentsystem.util.QrTokenUtil;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.springframework.beans.factory.annotation.Autowired;
import org.springframework.boot.test.context.SpringBootTest;
import org.springframework.test.annotation.DirtiesContext;
import org.springframework.test.context.ActiveProfiles;

import java.util.HashSet;
import java.util.Set;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatThrownBy;

@SpringBootTest
@ActiveProfiles("test")
@DirtiesContext(classMode = DirtiesContext.ClassMode.AFTER_CLASS)
class EventManagmnetSystemApplicationTests {

    @Autowired
    private EventRepository eventRepository;

    @Autowired
    private QrTokenUtil qrTokenUtil;

    @Autowired
    private EventCodeGenerator eventCodeGenerator;

    @Autowired
    private PassSeriesCodeGenerator passSeriesCodeGenerator;

    // ===== Utility Unit Tests =====

    @Test
    @DisplayName("UUID generation: raw QR token is 64 hex chars (256 bits)")
    void rawTokenIs256Bits() {
        String token = qrTokenUtil.generateRawToken();
        assertThat(token).hasSize(64); // 32 bytes hex-encoded = 64 chars
    }

    @Test
    @DisplayName("UUID generation: two tokens are never the same")
    void tokensAreUnique() {
        Set<String> tokens = new HashSet<>();
        for (int i = 0; i < 1000; i++) {
            tokens.add(qrTokenUtil.generateRawToken());
        }
        assertThat(tokens).hasSize(1000);
    }

    @Test
    @DisplayName("Token hashing: same token always yields same hash")
    void hashIsDeterministic() {
        String token = qrTokenUtil.generateRawToken();
        String hash1 = qrTokenUtil.hashToken(token);
        String hash2 = qrTokenUtil.hashToken(token);
        assertThat(hash1).isEqualTo(hash2);
    }

    @Test
    @DisplayName("Token hashing: different tokens yield different hashes")
    void differentTokensDifferentHashes() {
        String t1 = qrTokenUtil.generateRawToken();
        String t2 = qrTokenUtil.generateRawToken();
        assertThat(qrTokenUtil.hashToken(t1)).isNotEqualTo(qrTokenUtil.hashToken(t2));
    }

    @Test
    @DisplayName("Token hash is SHA-256 length (64 hex chars)")
    void hashLength() {
        String hash = qrTokenUtil.hashToken(qrTokenUtil.generateRawToken());
        assertThat(hash).hasSize(64);
    }

    @Test
    @DisplayName("EventCode: Renaissance Coffee Festival -> RCF")
    void eventCodeFromMultipleWords() {
        assertThat(eventCodeGenerator.generateFromName("Renaissance Coffee Festival")).isEqualTo("RCF");
    }

    @Test
    @DisplayName("EventCode: single word gets first characters")
    void eventCodeFromSingleWord() {
        String code = eventCodeGenerator.generateFromName("Symposium");
        assertThat(code).isNotEmpty();
        assertThat(code.length()).isGreaterThanOrEqualTo(1);
    }

    @Test
    @DisplayName("EventCode: valid code passes regex")
    void validCodePassesValidation() {
        assertThat(eventCodeGenerator.isValidCode("RFC")).isTrue();
        assertThat(eventCodeGenerator.isValidCode("RCF123")).isTrue();
        assertThat(eventCodeGenerator.isValidCode("A")).isFalse(); // too short
        assertThat(eventCodeGenerator.isValidCode("lowercase")).isFalse();
    }

    @Test
    @DisplayName("SeriesCode: is 8 uppercase alphanumeric chars")
    void seriesCodeFormat() {
        String code = passSeriesCodeGenerator.generate();
        assertThat(code).matches("^[A-Z0-9]{8}$");
    }

    @Test
    @DisplayName("SeriesCode: codes are unique across 1000 generations")
    void seriesCodesAreUnique() {
        Set<String> codes = new HashSet<>();
        for (int i = 0; i < 1000; i++) {
            codes.add(passSeriesCodeGenerator.generate());
        }
        assertThat(codes.size()).isGreaterThan(990);
    }

    // ===== Integration Tests =====

    @Test
    @DisplayName("BaseEntity: UUID is auto-generated on persist")
    void uuidAutoGenerated() {
        Event event = buildTestEvent("AUTO_UUID_TEST");
        Event saved = eventRepository.save(event);
        assertThat(saved.getId()).isNotNull();
    }

    @Test
    @DisplayName("BaseEntity: createdAt is set on persist and preserved on update")
    void createdAtImmutableAfterUpdate() {
        Event event = buildTestEvent("CREATED_AT_TEST");
        Event saved = eventRepository.save(event);
        var originalCreatedAt = saved.getCreatedAt();
        assertThat(originalCreatedAt).isNotNull();

        saved.setDescription("Updated description");
        Event updated = eventRepository.save(saved);
        assertThat(updated.getCreatedAt()).isEqualTo(originalCreatedAt);
    }

    @Test
    @DisplayName("BaseEntity: updatedAt is refreshed on update")
    void updatedAtChangesOnUpdate() throws InterruptedException {
        Event event = buildTestEvent("UPDATED_AT_TEST");
        Event saved = eventRepository.save(event);
        var originalUpdatedAt = saved.getUpdatedAt();

        Thread.sleep(10);
        saved.setDescription("New description");
        Event updated = eventRepository.save(saved);
        assertThat(updated.getUpdatedAt()).isAfterOrEqualTo(originalUpdatedAt);
    }

    @Test
    @DisplayName("Event: passSequenceCounter starts at 0")
    void passSequenceCounterStartsAtZero() {
        Event event = eventRepository.save(buildTestEvent("SEQ_COUNTER_TEST"));
        assertThat(event.getPassSequenceCounter()).isZero();
    }

    private Event buildTestEvent(String code) {
        Event event = new Event();
        event.setName("Test Event " + code);
        event.setEventCode(code);
        event.setPassSeriesCode("ABCD1234");
        event.setStatus(EventStatus.DRAFT);
        event.setActivationPolicy(ActivationPolicy.SELF_SERVICE);
        event.setCheckInPolicy(CheckInPolicy.SINGLE_ENTRY);
        event.setTimezone("UTC");
        return event;
    }
}
